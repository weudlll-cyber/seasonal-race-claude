#!/usr/bin/env bash
# ============================================================
# File:        website-route.sh
# Path:        deploy/website-route.sh
# Project:     RaceArena — WEBSITE-EMBED-1 piece 5a (2026-11-11)
# Description: THE RACE'S ROUTE FILE inside Seasonal Entertainment's proxy — ONE generator for both
#              proxy variants the website runs (nginx on the host, or Caddy in a container), and the
#              install step that puts the file in place, checks it with the proxy's own check, and
#              reloads the proxy — or takes the file out again.
#
#   bash website-route.sh render  --proxy nginx|caddy --race <host:port> --auth <host:port> --secret-file <f>
#   bash website-route.sh install --proxy nginx|caddy --race <host:port> --auth <host:port> --secret-file <f>
#                                 --routes-dir <dir> [--file <name>] [--exec "<prefix>"] [--config <f>]
#   bash website-route.sh remove  --proxy nginx|caddy --routes-dir <dir> [--file <name>] [--exec …] [--config …]
#
#   --race    where the proxy reaches the race (nginx: 127.0.0.1:<published port>; Caddy: the race's
#             container by its network alias, racearena:4000)
#   --auth    where the proxy reaches the website for the sign-in check (nginx: 127.0.0.1:<site-local-
#             port>; Caddy: site:3800)
#   --exec    the prefix the proxy's own commands run with — "" for nginx on the host, "docker exec
#             <the website's Caddy container>" for Caddy. The check and the reload run WHERE THE
#             PROXY RUNS, never a second copy of it.
#
# WHAT THE FILE DOES, for the base path /games/race — the website facts of 2026-11-11 (checked that
# day against website master 1292d1b and Bingo master; the morning sheet has them):
#   · EVERY path under /games/race/ reaches the race, the FULL path forwarded (nginx: proxy_pass with
#     no URI part; Caddy: `handle`, not `handle_path`). Nothing outside it reaches the race.
#   · On every path: the website's own session cookie (__Host-se.sid, se.sid) is STRIPPED from what is
#     forwarded, and any X-Acting-* or X-Ra-Proxy-Secret header the CLIENT sent is cleared.
#   · Only on /games/race/auth/website: the proxy asks the website GET /api/games/race/authorize —
#     that subrequest KEEPS the website cookie, it is how the website knows who is asking — and
#     forwards the identity headers the website answered with, plus the race's own proxy secret.
#     A 401 from the website is the answer the visitor gets; the race is not asked.
#
# ★ IT NEVER EDITS A WEBSITE-OWNED FILE. It writes, and removes, exactly one file of its own in the
#   website's routes folder (/etc/seasonal/routes), which the website's configuration includes.
#   The file carries the proxy secret (the proxy cannot read a file at run time), so it is written
#   0600; the secret is read from its own 0600 file and never printed.
# ============================================================
set -euo pipefail

# The identity headers the website's authorize answer carries (piece 3a reads exactly these).
IDENTITY_HEADERS=(X-Acting-User-Id X-Acting-User X-Acting-User-Roles X-Acting-User-Email-Verified
  X-Acting-User-Can-Host X-Acting-User-Steps X-Acting-Guest)
BASE=/games/race
SIGNIN="$BASE/auth/website"
AUTHORIZE=/api/games/race/authorize

die() { printf 'website-route: %s\n' "$*" >&2; exit 1; }

# nginx variable names for the headers the authorize answer carries: X-Acting-User-Id → ra_x_acting_user_id
nginx_var() { local h="${1,,}"; printf 'ra_%s' "${h//-/_}"; }

render_nginx() {
  local race="$1" auth="$2" secret="$3" h
  cat <<EOF
# RaceArena — its route inside Seasonal Entertainment (generated by deploy/website-route.sh; do not
# edit: \`racearena\` rewrites it). Included in the website's server block. Contains the race's proxy
# secret: mode 0600.

# The sign-in: the website says who is asking, the race is told, with its secret.
location = $SIGNIN {
    auth_request /_racearena_authorize;
EOF
  for h in "${IDENTITY_HEADERS[@]}"; do
    printf '    auth_request_set $%s $upstream_http_%s;\n' "$(nginx_var "$h")" "$(nginx_var "$h" | sed 's/^ra_//')"
  done
  printf '    set $ra_cookie $http_cookie;\n'
  render_nginx_cookie_strip
  render_nginx_common
  for h in "${IDENTITY_HEADERS[@]}"; do
    printf '    proxy_set_header %s $%s;\n' "$h" "$(nginx_var "$h")"
  done
  printf '    proxy_set_header X-Ra-Proxy-Secret "%s";\n' "$secret"
  printf '    proxy_pass http://%s;\n}\n\n' "$race"
  cat <<EOF
# The website's answer to "who is this?". Internal: no visitor can call it. The visitor's request
# headers — the website cookie with them — go to the website as they came.
location = /_racearena_authorize {
    internal;
    proxy_pass http://$auth$AUTHORIZE;
    proxy_pass_request_body off;
    proxy_set_header Content-Length "";
    proxy_set_header Host \$host;
    proxy_set_header X-Original-URI \$request_uri;
}

# Everything else of the race: the full path, no identity, no secret, no website cookie.
location $BASE/ {
    set \$ra_cookie \$http_cookie;
EOF
  render_nginx_cookie_strip
  render_nginx_common
  for h in "${IDENTITY_HEADERS[@]}"; do printf '    proxy_set_header %s "";\n' "$h"; done
  printf '    proxy_set_header X-Ra-Proxy-Secret "";\n'
  printf '    proxy_pass http://%s;\n}\n' "$race"
}

# The website cookie out of the Cookie header: both names, each up to twice (a browser sends a name
# once; twice covers a stale duplicate). `set` inside `if` is one of the two things nginx documents as
# safe there. ★ `se\.sid` is anchored on a cookie boundary, so `__Host-se.sid` does not half-match it.
render_nginx_cookie_strip() {
  local name
  for name in '__Host-se\.sid' 'se\.sid' '__Host-se\.sid' 'se\.sid'; do
    printf '    if ($ra_cookie ~ "^(.*?)(?:^|; *)%s=[^;]*(.*)$") { set $ra_cookie $1$2; }\n' "$name"
  done
  printf '    if ($ra_cookie ~ "^; *(.*)$") { set $ra_cookie $1; }\n'
}

# A location that sets any proxy_set_header inherits NONE from the server block, so the ordinary
# forwarding headers are set here again.
render_nginx_common() {
  cat <<'EOF'
    proxy_set_header Cookie $ra_cookie;
    proxy_set_header Host $host;
    proxy_set_header X-Forwarded-For $proxy_add_x_forwarded_for;
    proxy_set_header X-Forwarded-Proto $scheme;
    proxy_set_header X-Real-IP $remote_addr;
    proxy_http_version 1.1;
EOF
}

render_caddy() {
  local race="$1" auth="$2" secret="$3" h
  cat <<EOF
# RaceArena — its route inside Seasonal Entertainment (generated by deploy/website-route.sh; do not
# edit: \`racearena\` rewrites it). Imported in the website's site block. Contains the race's proxy
# secret: mode 0600.
#
# \`route\` keeps the order as written: Caddy's default order would run request_header AFTER
# forward_auth and remove the identity the website just gave.
handle $BASE/* {
	route {
		# Whatever the CLIENT sent as identity or secret, on every path.
EOF
  for h in "${IDENTITY_HEADERS[@]}"; do printf '\t\trequest_header -%s\n' "$h"; done
  cat <<EOF
		request_header -X-Ra-Proxy-Secret

		# The sign-in only: the website says who is asking (its cookie goes with the question).
		@ra_signin path $SIGNIN
		forward_auth @ra_signin $auth {
			uri $AUTHORIZE
			copy_headers ${IDENTITY_HEADERS[*]}
		}
		request_header @ra_signin X-Ra-Proxy-Secret "$secret"

		reverse_proxy $race {
			# The website cookie never reaches the race.
			header_up Cookie "(^|;\\s*)(__Host-se\\.sid|se\\.sid)=[^;]*" ""
			header_up Cookie "^;\\s*" ""
		}
	}
}
EOF
}

# ── the arguments ─────────────────────────────────────────────────────────────────────────────────
PROXY="" RACE="" AUTH="" SECRET_FILE="" ROUTES_DIR="" FILE="" EXEC="" CONFIG=""
parse() {
  while (($#)); do
    case "$1" in
      --proxy) PROXY="${2:-}"; shift 2 ;;
      --race) RACE="${2:-}"; shift 2 ;;
      --auth) AUTH="${2:-}"; shift 2 ;;
      --secret-file) SECRET_FILE="${2:-}"; shift 2 ;;
      --routes-dir) ROUTES_DIR="${2:-}"; shift 2 ;;
      --file) FILE="${2:-}"; shift 2 ;;
      --exec) EXEC="${2:-}"; shift 2 ;;
      --config) CONFIG="${2:-}"; shift 2 ;;
      *) die "unknown option: $1" ;;
    esac
  done
  [[ "$PROXY" == nginx || "$PROXY" == caddy ]] || die "--proxy must be nginx or caddy"
  [[ -n "$FILE" ]] || { if [[ "$PROXY" == nginx ]]; then FILE=racearena.conf; else FILE=racearena.caddy; fi; }
  [[ -n "$CONFIG" ]] || CONFIG=/etc/caddy/Caddyfile
}

render() {
  [[ -n "$RACE" && -n "$AUTH" && -r "$SECRET_FILE" ]] || die "render needs --race, --auth and a readable --secret-file"
  local secret
  secret="$(tr -d '\r\n' <"$SECRET_FILE")"
  [[ "$secret" =~ ^[A-Za-z0-9_-]{32,}$ ]] || die "the proxy secret is not 32+ URL-safe characters"
  if [[ "$PROXY" == nginx ]]; then render_nginx "$RACE" "$AUTH" "$secret"; else render_caddy "$RACE" "$AUTH" "$secret"; fi
}

# The proxy's own check and reload, where it runs. $EXEC is word-split on purpose (a command prefix).
proxy_check() {
  # shellcheck disable=SC2086
  if [[ "$PROXY" == nginx ]]; then $EXEC nginx -t -q; else $EXEC caddy validate --config "$CONFIG" --adapter caddyfile; fi
}
proxy_reload() {
  # shellcheck disable=SC2086
  if [[ "$PROXY" == nginx ]]; then $EXEC nginx -s reload; else $EXEC caddy reload --config "$CONFIG" --adapter caddyfile; fi
}

install_route() {
  [[ -d "$ROUTES_DIR" ]] || die "no routes folder at $ROUTES_DIR — the website marks its install with it"
  local target="$ROUTES_DIR/$FILE" log
  ( umask 077; render >"$target.tmp" )
  mv -f -- "$target.tmp" "$target"
  chmod 600 -- "$target"
  if ! log="$(proxy_check 2>&1)"; then
    # ★ ROLLBACK: the race's file out again, the proxy reloaded on the website's own configuration.
    rm -f -- "$target"
    proxy_reload >/dev/null 2>&1 || true
    die "the $PROXY check refused the route file, so it was removed again and the proxy reloaded without it:
$(printf '%s\n' "$log" | grep -v -i 'secret' | tail -n 5)"
  fi
  proxy_reload >/dev/null || die "the route file passed the $PROXY check but the reload failed"
  printf 'website-route: %s written, %s check passed, %s reloaded\n' "$target" "$PROXY" "$PROXY"
}

remove_route() {
  local target="$ROUTES_DIR/$FILE"
  if [[ -e "$target" ]]; then
    rm -f -- "$target"
    proxy_reload >/dev/null 2>&1 || die "$target removed, but the $PROXY reload failed"
    printf 'website-route: %s removed, %s reloaded\n' "$target" "$PROXY"
  else
    printf 'website-route: no route file at %s — nothing to remove\n' "$target"
  fi
}

main() {
  local cmd="${1:-}"
  shift || true
  parse "$@"
  case "$cmd" in
    render) render ;;
    install) install_route ;;
    remove) remove_route ;;
    *) die "usage: website-route.sh render|install|remove --proxy nginx|caddy … (see the header)" ;;
  esac
}

main "$@"
